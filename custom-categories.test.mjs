import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createApi } from './helpers/api.mjs';
test('owners manage categories, members use active keys, history and upload retries survive rename/archive', async () => {
  const api = await createApi();
  try {
    await api.start();
    const reg = async email => (await api.call('auth/register', { email, password: 'correct horse battery staple' })).json();
    const owner = await reg('owner@example.com'), member = await reg('member@example.com'), other = await reg('other@example.com');
    const household = await (await api.call('households', { name: 'Family' }, owner.token)).json();
    const base = `households/${household.id}`;
    const invite = await (await api.call('households/current/invites', {}, owner.token)).json();
    await api.call('invites/redeem', { code: invite.code }, member.token);
    const input = { type: 'Expense', name: 'Pets', colour: '#1565c0' };
    assert.equal((await api.call(`${base}/categories/save`, input)).status, 401);
    for (const user of [member, other]) assert.equal((await api.call(`${base}/categories/save`, input, user.token)).status, 403);
    for (const bad of [{ name: '' }, { name: 'x'.repeat(61) }, { colour: 'red' }, { colour: '#123456\n' }, { type: 'Other' }]) assert.equal((await api.call(`${base}/categories/save`, { ...input, ...bad }, owner.token)).status, 400);
    for (const name of ['Groceries', ' groceries ', 'Деца']) assert.equal((await api.call(`${base}/categories/save`, { ...input, name }, owner.token)).status, 409);
    const response = await api.call(`${base}/categories/save`, input, owner.token);
    assert.equal(response.status, 200);
    const category = await response.json();
    assert.equal(category.name, 'Pets'); assert.equal(category.colour, '#1565C0');
    assert.ok(category.key.startsWith('custom-'));
    assert.equal((await api.call(`${base}/categories/save`, { ...input, name: ' pets ' }, owner.token)).status, 409);
    const choices = async () => (await (await api.call(`${base}/expense-categories`, undefined, member.token)).json());
    assert.ok((await choices()).includes(category.key));
    const payload = { id: randomUUID(), amountMinor: 1000, category: category.key, occurredOn: '2026-11-16', authorName: 'Maya' };
    const entry = await (await api.call(`${base}/expenses`, payload, member.token)).json();
    assert.equal(entry.category, category.key);
    const renamed = await api.call(`${base}/categories/save`, { ...input, key: category.key, name: 'Animals' }, owner.token);
    assert.equal(renamed.status, 200);
    assert.equal((await renamed.json()).key, category.key);
    const current = async () => (await (await api.call('households/current', undefined, member.token)).json());
    assert.equal((await current()).catalog.find(c => c.key === category.key).name, 'Animals');
    for (const person of [member, other]) assert.equal((await api.call(`${base}/categories/archive`, { key: category.key, type: 'Expense' }, person.token)).status, 403);
    assert.equal((await api.call(`${base}/categories/archive`, { key: category.key, type: 'Expense' }, owner.token)).status, 204);
    assert.ok(!(await choices()).includes(category.key));
    assert.equal((await api.call(`${base}/expenses`, { ...payload, id: randomUUID() }, member.token)).status, 400);
    assert.equal((await api.call(`${base}/expenses`, payload, member.token)).status, 200, 'acknowledge previously accepted offline upload');
    const edited = await api.call(`${base}/transactions/${entry.id}/edit`, { revision: entry.revision, amountMinor: 2000, category: category.key, occurredOn: payload.occurredOn }, member.token);
    assert.equal(edited.status, 200, 'existing entry may retain archived category');
    assert.equal((await api.call(`${base}/categories/save`, { ...input, name: 'Animals' }, owner.token)).status, 409);
    await api.stop(); await api.start();
    const state = await current();
    assert.equal(state.household.budget.entries.length, 1);
    assert.equal(state.household.budget.entries[0].category, category.key);
    assert.equal(state.household.budget.entries[0].amountMinor, -2000);
    assert.equal(state.catalog.find(c => c.key === category.key).archived, true);
    assert.equal(state.catalog.find(c => c.key === category.key).name, 'Animals');
    const foreign = await (await api.call('households', { name: 'Other' }, other.token)).json();
    assert.equal((await api.call(`households/${foreign.id}/categories/archive`, { key: category.key, type: 'Expense' }, other.token)).status, 404);
    const incomeResponse = await api.call(`${base}/categories/save`, { ...input, type: 'Income', name: 'Side work' }, owner.token);
    assert.equal(incomeResponse.status, 200);
    const incomeCategory = await incomeResponse.json();
    assert.ok((await (await api.call(`${base}/income-categories`, undefined, member.token)).json()).includes(incomeCategory.key));
    assert.ok(!(await choices()).includes(incomeCategory.key));
    assert.equal((await api.call(`${base}/incomes`, { ...payload, id: randomUUID(), category: incomeCategory.key }, member.token)).status, 201);
    const races = await Promise.all([1,2].map(() => api.call(`${base}/categories/save`, { ...input, name: 'School' }, owner.token)));
    assert.deepEqual(races.map(r => r.status).sort(), [200,409]);
  } finally { await api.dispose(); }
});
